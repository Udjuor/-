'use strict';
const { contextBridge, ipcRenderer, webFrame } = require('electron');

// На сенсорной панели случайный щипок не должен масштабировать интерфейс.
webFrame.setVisualZoomLevelLimits(1, 1);

contextBridge.exposeInMainWorld('calendar', {
  language: ipcRenderer.sendSync('i18n:language'),
  setLanguage: (lang) => ipcRenderer.invoke('lang:set', lang),
  list: () => ipcRenderer.invoke('events:list'),
  save: (event, baseUpdatedAt) => ipcRenderer.invoke('events:save', event, baseUpdatedAt),
  saveMany: (events) => ipcRenderer.invoke('events:save-many', events),
  removeRange: (from, to, types) => ipcRenderer.invoke('events:remove-range', from, to, types),
  journal: () => ipcRenderer.invoke('journal:list'),
  portalStatus: () => ipcRenderer.invoke('portal:status'),
  setPortal: (on) => ipcRenderer.invoke('portal:set', on),
  setPortalAddress: (address) => ipcRenderer.invoke('portal:address', address),
  portalInfo: () => ipcRenderer.invoke('portal:info'),
  presenceToday: () => ipcRenderer.invoke('presence:today'),
  studentCode: (id) => ipcRenderer.invoke('student:code', id),
  unbindPhone: (id) => ipcRenderer.invoke('student:unbind', id),
  remove: (id, baseUpdatedAt) => ipcRenderer.invoke('events:remove', id, baseUpdatedAt),
  directory: () => ipcRenderer.invoke('directory:list'),
  saveRefs: (refs) => ipcRenderer.invoke('directory:save', refs),
  namePet: (groupId, name) => ipcRenderer.invoke('pet:name', groupId, name),
  removeRefs: (refs) => ipcRenderer.invoke('directory:remove', refs),
  attendance: () => ipcRenderer.invoke('attendance:list'),
  mark: (eventId, name, status, options) => ipcRenderer.invoke('attendance:mark', eventId, name, status, options),
  startLesson: (eventId, at) => ipcRenderer.invoke('attendance:start', eventId, at),
  lockReport: (eventId, excused) => ipcRenderer.invoke('attendance:lock', eventId, excused),
  saveReport: (fileName, text, labels) => ipcRenderer.invoke('report:save', fileName, text, labels),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  createMemo: (memo, fileName) => ipcRenderer.invoke('memo:create', memo, fileName),
  openMemo: () => ipcRenderer.invoke('memo:open'),
  revealMemo: () => ipcRenderer.invoke('memo:reveal'),
  finishSetup: () => ipcRenderer.invoke('setup:done'),
  setSize: (size) => ipcRenderer.invoke('size:set', size),
  printPaper: () => ipcRenderer.invoke('paper:print'),
  savePaperPdf: (fileName, title) => ipcRenderer.invoke('paper:pdf', fileName, title),
  setTheme: (theme) => ipcRenderer.invoke('theme:set', theme),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (settings) => ipcRenderer.invoke('settings:save', settings),
  syncStatus: () => ipcRenderer.invoke('sync:status'),
  syncNow: () => ipcRenderer.invoke('sync:now'),
  generateKey: () => ipcRenderer.invoke('sync:generate-key'),
  onChanged: (callback) => ipcRenderer.on('events:changed', () => callback()),
  minimize: () => ipcRenderer.invoke('window:minimize'),
  quit: () => ipcRenderer.invoke('window:quit'),
  onFullscreen: (callback) => ipcRenderer.on('window:fullscreen', (_e, full) => callback(full)),
  memoTemplate: () => ipcRenderer.invoke('memo:template'),
  uploadTemplate: (file) => ipcRenderer.invoke('memo:template-upload', file),
  downloadTemplate: () => ipcRenderer.invoke('memo:template-download'),
  resetTemplate: () => ipcRenderer.invoke('memo:template-reset'),
  backupStatus: () => ipcRenderer.invoke('backup:status'),
  backupNow: () => ipcRenderer.invoke('backup:now'),
  chooseBackupDir: () => ipcRenderer.invoke('backup:choose-dir'),
  restoreBackup: (folder) => ipcRenderer.invoke('backup:restore', folder),
  skipSplash: () => ipcRenderer.invoke('splash:skip'),
});
